// Build-time only: node packages/slides-effects/scripts/world-glyphs.cjs <JetBrainsMono-Regular.ttf> <OFL.txt>
// Requires msdfgen-wasm@1.0.0 and Python fonttools/uharfbuzz (FONTTOOLS_PYTHON selects the interpreter).
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { execFileSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { Msdfgen } = require("msdfgen-wasm");

async function main() {
  const root = path.resolve(__dirname, "../../..");
  const destination = path.join(root, "packages/slides-effects/packs/world");
  const [mono, license] = process.argv.slice(2);
  if (!mono || !license) throw new Error("Provide JetBrainsMono-Regular.ttf and its OFL.txt");
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "world-glyphs-"));
  try {
    execFileSync(process.env.FONTTOOLS_PYTHON ?? "python3", ["-c", `
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
import sys, json
import uharfbuzz as hb
for weight in [400, 500, 700]:
    font = TTFont(sys.argv[1])
    axes = {axis.axisTag: axis.defaultValue for axis in font['fvar'].axes}
    axes['wght'] = weight
    instantiateVariableFont(font, axes, inplace=True).save(sys.argv[2] + '/' + str(weight) + '.ttf')
faces = [sys.argv[2] + '/' + str(w) + '.ttf' for w in [400, 500, 700]] + [sys.argv[3]]
kernings = []
for file in faces:
    face = hb.Face(open(file, 'rb').read())
    font = hb.Font(face)
    def width(text):
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(font, buf, {'kern': True, 'liga': False, 'clig': False, 'calt': False})
        return sum(p.x_advance for p in buf.glyph_positions)
    advances = [width(chr(c)) for c in range(32, 127)]
    pairs = {}
    for a in range(95):
        for b in range(95):
            adjustment = width(chr(a + 32) + chr(b + 32)) - advances[a] - advances[b]
            if adjustment: pairs[a * 95 + b] = adjustment / face.upem
    kernings.append(pairs)
json.dump(kernings, open(sys.argv[2] + '/kerning.json', 'w'))
`, path.join(root, "packages/slides-web/assets/Roboto.ttf"), temporary, path.resolve(mono)]);
    const msdf = await Msdfgen.create(fs.readFileSync(require.resolve("msdfgen-wasm/wasm")));
    const first = 32, last = 126, em = 40, range = 8;
    const metrics = [], kernings = JSON.parse(fs.readFileSync(path.join(temporary, "kerning.json"), "utf8")), pixels = [];
    for (const file of [400, 500, 700].map(weight => path.join(temporary, `${weight}.ttf`)).concat(mono)) {
      msdf.loadFont(fs.readFileSync(file));
      msdf.loadGlyphs(Array.from({ length: last - first + 1 }, (_, index) => first + index));
      const face = [];
      for (let code = first; code <= last; code++) {
        const glyph = msdf.getGlyph(code);
        if (!glyph) throw new Error(`Font lacks ASCII ${code}`);
        const data = msdf.computeGlpyhMsdfData(glyph, { size: em, range, edgeColoring: "inktrap" });
        face.push([glyph.advance, data.xTranslate, data.yTranslate, data.width, data.height, pixels.length]);
        if (data.width && data.height) {
          const bitmap = msdf.generateBitmap(glyph, data);
          for (const pixel of bitmap.data) pixels.push(pixel & 0xffffff);
        }
      }
      metrics.push(face);
    }
    // PackBits-style RGB packets: literals (1..128 pixels), or repeated colors (2..129).
    const bytes = [];
    const rgb = pixel => bytes.push(pixel & 255, pixel >>> 8 & 255, pixel >>> 16 & 255);
    let index = 0;
    const run = start => { let end = start + 1; while (end < pixels.length && end < start + 129 && pixels[end] === pixels[start]) end++; return end - start; };
    while (index < pixels.length) {
      const count = run(index);
      if (count >= 2) { bytes.push(128 + count - 2); rgb(pixels[index]); index += count; }
      else {
        const start = index++;
        while (index < pixels.length && index < start + 128 && run(index) < 2) index++;
        bytes.push(index - start - 1);
        for (let i = start; i < index; i++) rgb(pixels[i]);
      }
    }
    const round = (_key, value) => typeof value === "number" ? Math.round(value * 1e7) / 1e7 : value;
    const hash = file => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
    fs.writeFileSync(path.join(destination, "glyphs.ts"), `// Generated by scripts/world-glyphs.cjs. RGB MSDF; Roboto 400/500/700, JetBrains Mono 400.\n` +
      `// Source SHA-256: Roboto ${hash(path.join(root, "packages/slides-web/assets/Roboto.ttf"))}; mono ${hash(mono)}.\n` +
      `export const glyphFirst = ${first}, glyphLast = ${last}, glyphEm = ${em}, glyphRange = ${range}, glyphPixelCount = ${pixels.length};\n` +
      `// Per glyph: advance, x/y translation (em), width/height (px), pixel offset. Rows top-down.\n` +
      `export const glyphMetrics = ${JSON.stringify(metrics, round)};\n` +
      `export const glyphKernings: Record<number, number>[] = ${JSON.stringify(kernings, round)};\n` +
      `export const glyphAtlas = "${Buffer.from(bytes).toString("base64")}";\n`);
    fs.writeFileSync(path.join(destination, "font-licenses.json"), JSON.stringify({
      Roboto: fs.readFileSync(path.join(root, "packages/slides-web/assets/OFL.txt"), "utf8"),
      "JetBrains Mono": fs.readFileSync(license, "utf8"),
    }, null, 2) + "\n");
    console.log(JSON.stringify({ pixels: pixels.length, gpuPixelBytes: pixels.length * 4, packedBytes: bytes.length }));
  } finally { fs.rmSync(temporary, { recursive: true, force: true }); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
