// Bakes printable ASCII from Roboto into the World pack's signed-distance glyph atlas.
// Run from the repository root: swift packages/slides-effects/scripts/world-glyphs.swift
import CoreGraphics
import CoreText
import Foundation

let cell = 32, em = 20.0, spread = 4.0, baseline = 8.0, oversample = 4
let first = 32, last = 126
let fontURL = URL(fileURLWithPath: "packages/slides-web/assets/Roboto.ttf")
guard let provider = CGDataProvider(url: fontURL as CFURL), let graphicsFont = CGFont(provider) else { fatalError("Cannot load \(fontURL.path)") }
let font = CTFontCreateWithGraphicsFont(graphicsFont, CGFloat(em) * CGFloat(oversample), nil, nil)
let size = cell * oversample
var atlas = [UInt8](repeating: 0, count: (last - first + 1) * cell * cell)
var advances: [Double] = []

for code in first...last {
  var character = UniChar(code), glyph = CGGlyph(0)
  CTFontGetGlyphsForCharacters(font, &character, &glyph, 1)
  var advance = CGSize.zero
  CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
  advances.append(Double(advance.width) / (em * Double(oversample)))
  var pixels = [UInt8](repeating: 0, count: size * size)
  pixels.withUnsafeMutableBytes { buffer in
    let context = CGContext(data: buffer.baseAddress, width: size, height: size, bitsPerComponent: 8, bytesPerRow: size,
      space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    context.setFillColor(gray: 1, alpha: 1)
    var position = CGPoint(x: spread * Double(oversample), y: baseline * Double(oversample))
    CTFontDrawGlyphs(font, &glyph, &position, 1, context)
  }
  // Bitmap memory runs top-down, so row 0 is the cell's top edge and the baseline sits `baseline` px above the bottom.
  let inside = { (x: Int, y: Int) -> Bool in x >= 0 && y >= 0 && x < size && y < size && pixels[y * size + x] > 127 }
  let radius = Int(spread) * oversample
  for y in 0..<cell {
    for x in 0..<cell {
      let sx = x * oversample + oversample / 2, sy = y * oversample + oversample / 2
      let center = inside(sx, sy)
      var nearest = Double(radius)
      for dy in -radius...radius {
        for dx in -radius...radius where inside(sx + dx, sy + dy) != center {
          nearest = min(nearest, (Double(dx * dx + dy * dy)).squareRoot())
        }
      }
      let distance = (center ? nearest : -nearest) / Double(oversample)
      atlas[(code - first) * cell * cell + y * cell + x] = UInt8(max(0, min(255, (128 + distance / spread * 127).rounded())))
    }
  }
}

let header = """
// Generated by packages/slides-effects/scripts/world-glyphs.swift from Roboto (Apache-2.0). Do not edit.
// ASCII \(first)-\(last), \(cell)x\(cell) cells, em \(Int(em))px, rows top-down, baseline \(Int(baseline))px above the bottom edge, distance range \(Int(spread))px.

"""
let body = """
export const glyphCell = \(cell), glyphEm = \(Int(em)), glyphSpread = \(Int(spread)), glyphBaseline = \(Int(baseline)), glyphFirst = \(first), glyphLast = \(last);
export const glyphAdvances = [\(advances.map { String(format: "%.4f", $0) }.joined(separator: ","))];
export const glyphAtlas = "\(Data(atlas).base64EncodedString())";

"""
try (header + body).write(toFile: "packages/slides-effects/packs/world/glyphs.ts", atomically: true, encoding: .utf8)
print("wrote \(atlas.count) atlas bytes")
