import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { transformSync } from "@babel/core";
import reactNativePreset from "@react-native/babel-preset";
import { editableDiffFiles } from "../apps/diff/src/customization/diffCustomizationModel.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function resolveImport(from, name) {
  return path.posix.normalize(path.posix.join(path.posix.dirname(from), name));
}

export function readDiffCustomizationBaseline() {
  const sourceRoot = path.join(root, "apps/diff/src");
  const files = Object.fromEntries(editableDiffFiles.map(file => [file, fs.readFileSync(path.join(sourceRoot, file), "utf8")]));
  const hosts = { react: "react", "react/jsx-runtime": "react/jsx-runtime", "react/jsx-dev-runtime": "react/jsx-runtime" };
  for (const [file, contents] of Object.entries(files)) {
    const transpiler = new Bun.Transpiler({ loader: file.endsWith("tsx") ? "tsx" : "ts" });
    const imports = [...transpiler.scan(contents).imports, ...[...contents.matchAll(/require\("([^"]+)"\)/g)].map(match => ({ path: match[1] }))];
    for (const { path: name } of imports) {
      if (!name.startsWith(".")) hosts[name] = name;
      else {
        const relative = resolveImport(file, name);
        if (editableDiffFiles.some(editable => editable.replace(/\.tsx?$/, "") === relative)) continue;
        const source = [relative, `${relative}.ts`, `${relative}.tsx`].find(candidate => fs.existsSync(path.join(sourceRoot, candidate)));
        if (!source) throw new Error(`Missing customization host import: ${relative}`);
        hosts[`diff-host/${relative}`] = source;
      }
    }
  }
  const version = JSON.parse(fs.readFileSync(path.join(root, "apps/diff/package.json"), "utf8")).version;
  const baseId = `${version}:${createHash("sha256").update(JSON.stringify({ files, hosts })).digest("hex")}`;
  return { baseId, files, hosts };
}

export function writeDiffCustomizationHosts(baseline = readDiffCustomizationBaseline()) {
  const entries = Object.entries(baseline.hosts);
  const imports = entries.map(([name, source], index) => name.startsWith("diff-host/") && /\.png$/.test(source)
    ? `const host${index} = require(${JSON.stringify(`../${source}`)});`
    : `import * as host${index} from ${JSON.stringify(name.startsWith("diff-host/") ? `../${source.replace(/\.tsx?$/, "")}` : source)};`).join("\n");
  const code = `// Generated by scripts/diff-customization.mjs --hosts.\n${imports}\n\nexport const diffCustomizationHosts: Record<string, unknown> = {\n${entries.map(([name], index) => `  ${JSON.stringify(name)}: host${index},`).join("\n")}\n};\n`;
  const destination = path.join(root, "apps/diff/src/customization/diffCustomizationHosts.generated.ts");
  if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== code) fs.writeFileSync(destination, code);
}

export async function compileDiffCustomization(baseline, files) {
  if (!files || Object.keys(files).length !== editableDiffFiles.length ||
    editableDiffFiles.some(file => typeof files[file] !== "string" || files[file].length > 500_000)) throw new Error("Invalid customization source files.");
  const errors = [];
  const output = await Bun.build({
    entrypoints: ["/DiffViewerWindow.tsx"],
    target: "browser",
    format: "cjs",
    jsx: { runtime: "automatic", development: false },
    define: { __DEV__: "false", "process.env.NODE_ENV": '"production"' },
    plugins: [{ name: "diff-customization", setup(build) {
      build.onResolve({ filter: /.*/ }, (args) => {
        const relative = !args.importer ? args.path.slice(1) : args.path.startsWith(".") ? resolveImport(args.importer, args.path) : null;
        const file = relative && [relative, `${relative}.ts`, `${relative}.tsx`].find(candidate => Object.hasOwn(files, candidate));
        if (file) return { path: file, namespace: "diff-customization" };
        const host = relative ? `diff-host/${relative}` : args.path;
        if (!Object.hasOwn(baseline.hosts, host)) {
          const message = `Unavailable import: ${args.path}. Customizations can use only the app's existing modules.`;
          errors.push(message);
          throw new Error(message);
        }
        return { path: host, external: true };
      });
      build.onLoad({ filter: /.*/, namespace: "diff-customization" }, args => ({
        contents: files[args.path].replace(/(from\s*|require\(\s*|import\s*)["'](\.[^"']+)["']/g, (match, prefix, name) => {
          const relative = resolveImport(args.path, name);
          return Object.hasOwn(baseline.hosts, `diff-host/${relative}`) ? `${prefix}${JSON.stringify(`diff-host/${relative}`)}` : match;
        }),
        loader: args.path.endsWith("tsx") ? "tsx" : "ts",
      }));
    } }],
  }).catch(error => { throw new Error(errors.join("\n") || String(error)); });
  if (!output.success) throw new Error(output.logs.map(String).join("\n"));
  const bundled = await output.outputs[0].text();
  const code = transformSync(bundled, { filename: "diff-customization.js", babelrc: false, configFile: false,
    presets: [[reactNativePreset, { enableBabelRuntime: false, unstable_transformProfile: "hermes-canary" }]], compact: false }).code;
  if (code.length > 2_000_000) throw new Error("The customization is too large.");
  return { baseId: baseline.baseId, code };
}

if (import.meta.main) {
  try {
    const baseline = typeof __DIFF_BASELINE__ === "undefined" ? readDiffCustomizationBaseline() : __DIFF_BASELINE__;
    if (process.argv.includes("--hosts")) writeDiffCustomizationHosts(baseline);
    else if (process.argv.includes("--baseline")) process.stdout.write(JSON.stringify({ baseId: baseline.baseId, files: baseline.files }));
    else {
      const request = JSON.parse(await Bun.stdin.text());
      if (request.baseId !== baseline.baseId) throw new Error("The app changed. Recreate customizations against this version.");
      process.stdout.write(JSON.stringify(await compileDiffCustomization(baseline, request.files)));
    }
  } catch (error) {
    process.stderr.write(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
